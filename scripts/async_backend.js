// Generates the Postgres business layer from the SQLite source and makes shared
// HTTP/auth handlers await either backend. No credentials are read by this script.
const fs=require('fs');
const parser=require('@babel/parser');
const traverse=require('@babel/traverse').default;
const generate=require('@babel/generator').default;
const t=require('@babel/types');
const pure=new Set(['calculateHaversine','formatTaskRow']);
const business=parser.parse(fs.readFileSync('server/db-sqlite.js','utf8'));
const names=new Set();
traverse(business,{FunctionDeclaration(p){if(!pure.has(p.node.id.name))names.add(p.node.id.name)}});
for(const name of ['sessionToken','session','issue','parentAccess'])names.add(name);
function transform(source){
 const ast=parser.parse(source);
 const transactional=new Set();
 traverse(ast,{VariableDeclarator(p){const n=p.node.init;if(t.isCallExpression(n)&&t.isMemberExpression(n.callee)&&n.callee.property.name==='transaction'&&t.isIdentifier(p.node.id))transactional.add(p.node.id.name)}});
 traverse(ast,{CallExpression:{exit(p){
  if(t.isAwaitExpression(p.parent))return;
  const c=p.node.callee;
  const direct=t.isIdentifier(c)&&(names.has(c.name)||transactional.has(c.name));
  const member=t.isMemberExpression(c)&&(c.property.name==='exec'&&t.isIdentifier(c.object,{name:'db'})||c.property.name==='close'&&t.isIdentifier(c.object,{name:'db'})||['get','all','run'].includes(c.property.name)&&t.isCallExpression(c.object)&&t.isMemberExpression(c.object.callee)&&c.object.callee.property.name==='prepare'||t.isIdentifier(c.object,{name:'access'})&&c.property.name==='session'||t.isIdentifier(c.object,{name:'whatsapp'})&&['init','start'].includes(c.property.name)||t.isCallExpression(c.object)&&c.property.name==='install');
  if(!direct&&!member)return;
  const owner=p.getFunctionParent();if(!owner)throw Error('Wrap asynchronous module startup before transforming.');
  owner.node.async=true;p.replaceWith(t.awaitExpression(p.node));
 }}});
 return generate(ast,{comments:true}).code+'\n';
}
let source=fs.readFileSync('server/db-sqlite.js','utf8');
source=source.slice(source.indexOf('function initDatabase'));
source="const path=require('path'); const fs=require('fs'); const crypto=require('crypto'); const db=require('./postgres-db').connect();\n"+source;
// Every exported business function except pure formatting/math may read the database.
source=transform(source);
const cloudAst=parser.parse(source);
traverse(cloudAst,{FunctionDeclaration(p){if(names.has(p.node.id.name))p.node.async=true}});
source=generate(cloudAst).code+'\n';
fs.writeFileSync('server/db-postgres.js','// Generated by scripts/async_backend.js; edit db-sqlite.js then regenerate.\n'+source);
